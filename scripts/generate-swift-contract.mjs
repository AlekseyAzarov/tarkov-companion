#!/usr/bin/env node
// Generates sdk-ios/Sources/TarkovCompanion/Generated/GeneratedContract.swift
// from contracts/ and VERSION, as buildSrc/GenerateContractSourcesTask.kt does
// for Kotlin:
//
//   - config-limits.json: `key<Name>` for each settings key, `<name><Attribute>`
//     for its limits and defaults, `<section>Keys`, and the shared constants;
//   - every names contract with a `generate.swift` prefix: `<prefix><Group><Name>`.
//
// Run it before building sdk-ios; CI does (.github/workflows/ci.yml).
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const contractsDirectory = fileURLToPath(new URL('../contracts/', import.meta.url));
const versionFile = fileURLToPath(new URL('../VERSION', import.meta.url));
const outputFile = fileURLToPath(
  new URL('../sdk-ios/Sources/TarkovCompanion/Generated/GeneratedContract.swift', import.meta.url),
);

const settingsSections = ['config', 'profile', 'bridgeOptions', 'shared'];

// sell_flea -> SellFlea, timeoutMilliseconds -> TimeoutMilliseconds
const pascalCase = (name) =>
  name
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');

const lowerFirst = (name) => name.charAt(0).toLowerCase() + name.slice(1);

function swiftLiteral(value, path) {
  if (Number.isInteger(value)) {
    return String(value);
  }

  if (typeof value === 'string') {
    return JSON.stringify(value);
  }

  throw new Error(`config-limits.json: ${path} must be an integer or a string`);
}

function settingsLines() {
  const limits = JSON.parse(readFileSync(`${contractsDirectory}config-limits.json`, 'utf8'));
  const lines = [];

  for (const section of settingsSections) {
    const entries = limits[section];
    if (!entries) {
      throw new Error(`config-limits.json: missing "${section}"`);
    }

    lines.push(`// config-limits.json: ${section}`);
    const settingsKeys = [];
    for (const [key, value] of Object.entries(entries)) {
      if (typeof value !== 'object') {
        lines.push(`static let ${key} = ${swiftLiteral(value, `${section}.${key}`)}`);
        continue;
      }

      settingsKeys.push(key);
      lines.push(`static let key${pascalCase(key)} = "${key}"`);
      for (const [attribute, attributeValue] of Object.entries(value)) {
        const literal = swiftLiteral(attributeValue, `${section}.${key}.${attribute}`);
        lines.push(`static let ${key}${pascalCase(attribute)} = ${literal}`);
      }
    }

    if (settingsKeys.length > 0) {
      const keySet = settingsKeys.map((key) => `"${key}"`).join(', ');
      lines.push(`static let ${section}Keys: Set<String> = [${keySet}]`);
    }
    lines.push('');
  }

  return lines;
}

function namesContractLines(fileName) {
  const contract = JSON.parse(readFileSync(`${contractsDirectory}${fileName}`, 'utf8'));
  const prefix = contract.generate?.swift;
  if (!contract.names || prefix === undefined) {
    return [];
  }

  const lines = [`// ${fileName}`];
  for (const [group, wireNames] of Object.entries(contract.names)) {
    const groupName = prefix === '' ? lowerFirst(group) : `${prefix}${group}`;
    for (const wireName of wireNames) {
      lines.push(`static let ${groupName}${pascalCase(wireName)} = "${wireName}"`);
    }
  }
  lines.push('');

  return lines;
}

const version = readFileSync(versionFile, 'utf8').trim();
if (!/^\d+\.\d+\.\d+(-[\w.]+)?$/.test(version)) {
  throw new Error(`VERSION is not semver: '${version}'`);
}

const contractFileNames = readdirSync(contractsDirectory)
  .filter((fileName) => fileName.endsWith('.json'))
  .sort();
const bodyLines = [
  `static let sdkVersion = "${version}"`,
  '',
  ...settingsLines(),
  ...contractFileNames.flatMap(namesContractLines),
];
while (bodyLines.at(-1) === '') {
  bodyLines.pop();
}

const content = [
  '// Generated by scripts/generate-swift-contract.mjs from contracts/. Do not edit.',
  '',
  'enum GeneratedContract {',
  ...bodyLines.map((line) => (line === '' ? '' : `    ${line}`)),
  '}',
  '',
].join('\n');

// Only touched when the content changed, so SwiftPM doesn't rebuild for nothing.
if (!existsSync(outputFile) || readFileSync(outputFile, 'utf8') !== content) {
  mkdirSync(dirname(outputFile), { recursive: true });
  writeFileSync(outputFile, content);
}
