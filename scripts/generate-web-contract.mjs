#!/usr/bin/env node
// Generates web-ui/src/generated/contract.ts from the names contracts in
// contracts/ (those with a `generate.typescript` prefix). For each group:
//
//   export const BridgeRequest = { Hello: 'hello', ... } as const;
//   export type BridgeRequestName = (typeof BridgeRequest)[keyof typeof BridgeRequest];
//
// web-ui/build.mjs imports this file, and npm runs it before typecheck and tests.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const contractsDirectory = fileURLToPath(new URL('../contracts/', import.meta.url));
const outputFile = fileURLToPath(new URL('../web-ui/src/generated/contract.ts', import.meta.url));

// sell_flea -> SellFlea, minimumNativeProtocol -> MinimumNativeProtocol
const pascalCase = (name) =>
  name
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');

function generatedLinesFor(fileName) {
  const contract = JSON.parse(readFileSync(`${contractsDirectory}${fileName}`, 'utf8'));
  const prefix = contract.generate?.typescript;
  if (!contract.names || prefix === undefined) {
    return [];
  }

  const lines = [`// ${fileName}`];
  for (const [group, wireNames] of Object.entries(contract.names)) {
    const objectName = `${prefix}${group}`;
    lines.push(`export const ${objectName} = {`);
    for (const wireName of wireNames) {
      lines.push(`  ${pascalCase(wireName)}: '${wireName}',`);
    }
    lines.push('} as const;');
    lines.push(`export type ${objectName}Name = (typeof ${objectName})[keyof typeof ${objectName}];`);
    lines.push('');
  }

  return lines;
}

const contractFileNames = readdirSync(contractsDirectory)
  .filter((fileName) => fileName.endsWith('.json'))
  .sort();
const content = [
  '// Generated by scripts/generate-web-contract.mjs from contracts/. Do not edit.',
  '',
  ...contractFileNames.flatMap(generatedLinesFor),
].join('\n');

// Only touched when the content changed, so watchers don't rebuild for nothing.
if (!existsSync(outputFile) || readFileSync(outputFile, 'utf8') !== content) {
  mkdirSync(dirname(outputFile), { recursive: true });
  writeFileSync(outputFile, content);
}
