import groovy.json.JsonSlurper
import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File

/**
 * Kotlin constants from `contracts/` and `VERSION`. The core generates its C++
 * constants from the same files (core/cmake/contract.cmake).
 */
@CacheableTask
abstract class GenerateContractSourcesTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val limitsFile: RegularFileProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val analyticsFile: RegularFileProperty

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val contractFiles: ConfigurableFileCollection

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val versionFile: RegularFileProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val version = versionFile.get().asFile.readText().trim()
        require(Regex("""\d+\.\d+\.\d+(-[\w.]+)?""").matches(version)) { "VERSION is not semver: '$version'" }

        @Suppress("UNCHECKED_CAST")
        val limits = JsonSlurper().parse(limitsFile.get().asFile) as Map<String, Any?>
        val sections = SECTIONS.map { section ->
            @Suppress("UNCHECKED_CAST")
            val entries = limits[section] as? Map<String, Any?> ?: error("config-limits.json: missing \"$section\"")
            generateSection(section, entries)
        }
        val namesContracts = contractFiles.files.sortedBy(File::getName).mapNotNull(::generateNamesContract)
        val allSections = sections + listOf(generateAnalytics()) + namesContracts

        val generatedPackage = packageName.get()
        val packageDirectory = outputDirectory.get().asFile.resolve(generatedPackage.replace('.', '/'))
        packageDirectory.mkdirs()
        packageDirectory.resolve("GeneratedContract.kt").writeText(
            buildString {
                appendLine("// Generated by GenerateContractSourcesTask from contracts/. Do not edit.")
                appendLine("package $generatedPackage")
                appendLine()
                appendLine("internal object GeneratedContract {")
                appendLine("    const val SDK_VERSION: String = \"$version\"")
                allSections.forEach { lines ->
                    appendLine()
                    lines.forEach { line -> appendLine("    $line") }
                }
                appendLine("}")
            },
        )
    }

    /**
     * `EVENT_<NAME>` and `PROPERTY_<NAME>` constants for analytics-events.json,
     * plus `EVENT_PROPERTIES` (event -> allowed properties) for the runtime check.
     */
    private fun generateAnalytics(): List<String> {
        @Suppress("UNCHECKED_CAST")
        val catalog = JsonSlurper().parse(analyticsFile.get().asFile) as Map<String, Any?>
        @Suppress("UNCHECKED_CAST")
        val events = catalog["events"] as? Map<String, Map<String, Any?>>
            ?: error("analytics-events.json: missing \"events\"")
        val propertiesByEvent = events.mapValues { (event, specification) ->
            @Suppress("UNCHECKED_CAST")
            specification["properties"] as? List<String> ?: error("analytics-events.json: $event has no \"properties\" list")
        }

        val lines = mutableListOf(constant("WEB_EVENT_PREFIX", catalog["webEventPrefix"], "webEventPrefix"))
        events.keys.sorted().forEach { event ->
            lines += "const val EVENT_${event.uppercase()}: String = \"$event\""
        }
        propertiesByEvent.values.flatten().toSortedSet().forEach { property ->
            lines += "const val PROPERTY_${property.uppercase()}: String = \"$property\""
        }

        val table = propertiesByEvent.entries.joinToString(
            separator = ",\n        ",
            prefix = "\n        ",
            postfix = ",\n    ",
        ) { (event, properties) ->
            "\"$event\" to setOf(${properties.joinToString { property -> "\"$property\"" }})"
        }
        lines += "val EVENT_PROPERTIES: Map<String, Set<String>> = mapOf($table)"

        return lines
    }

    /**
     * A names contract maps groups to wire names: `<PREFIX>_<GROUP>_<NAME>` for
     * each, with the prefix from `generate.kotlin` (none when it is empty).
     * Null for other files and for contracts not generated for Kotlin.
     */
    private fun generateNamesContract(file: File): List<String>? {
        @Suppress("UNCHECKED_CAST")
        val contract = JsonSlurper().parse(file) as Map<String, Any?>
        @Suppress("UNCHECKED_CAST")
        val namesByGroup = contract["names"] as? Map<String, List<String>> ?: return null
        @Suppress("UNCHECKED_CAST")
        val prefix = (contract["generate"] as? Map<String, Any?>)?.get("kotlin") as? String ?: return null

        val lines = mutableListOf("// ${file.name}")
        for ((group, wireNames) in namesByGroup) {
            for (wireName in wireNames) {
                val constant = listOf(prefix, constantName(group), constantName(wireName))
                    .filter { part -> part.isNotEmpty() }
                    .joinToString("_")
                lines += "const val $constant: String = \"$wireName\""
            }
        }

        return lines
    }

    /**
     * A section maps keys either to an object of attributes (a settings key:
     * `KEY_<NAME>` plus `<NAME>_<ATTRIBUTE>` constants and a `<SECTION>_KEYS`
     * set) or to a plain value (a shared constant).
     */
    private fun generateSection(section: String, entries: Map<String, Any?>): List<String> {
        val lines = mutableListOf<String>()
        val settingsKeys = mutableListOf<String>()
        for ((key, value) in entries) {
            val name = constantName(key)
            if (value !is Map<*, *>) {
                lines += constant(name, value, "$section.$key")
                continue
            }

            settingsKeys += key
            lines += "const val KEY_$name: String = \"$key\""
            for ((attribute, attributeValue) in value) {
                val attributeName = "${name}_${constantName(attribute.toString())}"
                lines += constant(attributeName, attributeValue, "$section.$key.$attribute")
            }
        }

        if (settingsKeys.isNotEmpty()) {
            val keySet = settingsKeys.joinToString { key -> "\"$key\"" }
            lines += "val ${constantName(section)}_KEYS: Set<String> = setOf($keySet)"
        }

        return lines
    }

    private fun constant(name: String, value: Any?, path: String): String = when (value) {
        is Int -> "const val $name: Int = $value"
        is String -> "const val $name: String = \"$value\""
        else -> error("config-limits.json: $path must be an integer or a string")
    }

    // itemCacheCapacity -> ITEM_CACHE_CAPACITY, cache_read -> CACHE_READ
    private fun constantName(camelCase: String): String =
        camelCase.replace(Regex("([a-z0-9])([A-Z])"), "$1_$2").uppercase()

    private companion object {
        val SECTIONS = listOf("config", "profile", "bridgeOptions", "shared")
    }
}
